import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

import { colorStyles } from "enarratio";
import { createElement } from "react";
import { renderToString } from "react-dom/server";
import { describe, expect, it } from "vitest";

import {
  EmailCategoryChart,
  RecoveryRateChart,
  RecoveryTimingChart,
  RevenueChart,
} from "~/components/recovery-dashboard-charts";
import { drawExpiringCardsTimeline } from "~/lib/audit/timeline";
import { drawCohorts, drawLatestMovement } from "~/lib/dashboard/console-charts";
import type { RecoveryDashboardWindow } from "~/lib/dashboard/recovery-window.server";
import { drawChurnRate } from "~/lib/intelligence/churn";
import { drawHealthHistory } from "~/lib/intelligence/customer-detail";
import { drawHealth, drawMovement, drawMrrTrend, drawNrr, drawPlans } from "~/lib/intelligence/dashboard-charts";
import { drawStepPerformance } from "~/lib/recovery/sequence-chart";

// Recova's chart colors are Foxhound's own tokens (--green, --blue, ...), not
// Capsomer's, so capsomer/enarratio.css cannot theme them and the CSP refuses
// an inline <style>. app/components/chart-colors.css is Enarratio's
// colorStyles() over every chart Foxhound draws, and this test fails when a
// chart gains or changes a color pair without it, which would otherwise
// leave that series silently in the default palette.
// To regenerate: UPDATE_CHART_COLORS=1 npx vitest run test/chart-colors.test.ts

const FILE = fileURLToPath(new URL("../app/components/chart-colors.css", import.meta.url));
const HEADER = `/* Generated by test/chart-colors.test.ts from every chart's colors: Enarratio's
   colorStyles(). Do not edit; run UPDATE_CHART_COLORS=1 npx vitest run test/chart-colors.test.ts. */
`;

const W = 600;
const day = (n: number) => new Date(Date.UTC(2026, 0, n));
const movement = { newMrrCents: 500, expansionMrrCents: 200, contractionMrrCents: 100, churnMrrCents: 50, reactivationMrrCents: 20 };

// Only the fields each chart reads; the rest of the window is not drawn.
const w = {
  rangeLabel: "Last 7 days",
  rangeDays: 7,
  recoveryRateDaily: [
    { date: "2026-01-01", rate: 10 },
    { date: "2026-01-02", rate: 20 },
  ],
  recoveredPayments: [{ recoveredAt: day(1), amountCents: 1000, currency: "usd" }],
  recoveredRevenue: [],
  emailsSentInRange: { sent: 1, openRatePct: 50, clickRatePct: 10 },
  emailCategoryPerformance: [{ category: "soft", openRatePct: 50, clickRatePct: 10, emailCount: 2 }],
  recoveryTimingBuckets: [{ dayBucket: "Day 1", count: 1, percentage: 100 }],
} as unknown as RecoveryDashboardWindow;

function everyChart(): string[] {
  return [
    renderToString(createElement(RecoveryRateChart, { w })),
    renderToString(createElement(RevenueChart, { w, nowMs: day(2).getTime() })),
    renderToString(createElement(EmailCategoryChart, { w })),
    renderToString(createElement(RecoveryTimingChart, { w })),
    drawMrrTrend([{ at: day(1), totalMrrCents: 100 }, { at: day(2), totalMrrCents: 200 }], "usd", W),
    drawNrr([{ at: day(1), nrrPct: 100 }, { at: day(2), nrrPct: 101 }], W),
    drawMovement([{ at: day(5), ...movement }], "usd", W),
    drawPlans([{ plan: "Pro", mrrCents: 100 }], "usd", W),
    drawHealth([{ date: "2026-01-01", atRisk: 1, watch: 2, healthy: 3 }], W),
    // The line takes the latest score's band: one chart per band.
    ...[10, 50, 90].map((score) =>
      drawHealthHistory([{ recordedAt: day(1), healthScore: 50 }, { recordedAt: day(2), healthScore: score }], W),
    ),
    drawLatestMovement(movement, "usd", W),
    drawCohorts([{ label: "Jan 2026", values: [90] }], W),
    // Equal months draw one series, unequal months two.
    drawExpiringCardsTimeline([{ label: "Oct 2026", count: 2 }], W),
    drawExpiringCardsTimeline([{ label: "Oct 2026", count: 2 }, { label: "Nov 2026", count: 1 }], W),
    drawChurnRate([{ at: day(1), voluntaryPct: 1, involuntaryPct: 2 }, { at: day(2), voluntaryPct: 1, involuntaryPct: 2 }], W),
    drawStepPerformance([{ stepType: "email", label: "Day 1 email", sent: 3, openRatePct: 50, clickRatePct: 10, recoveryRatePct: 5 }], W),
  ];
}

describe("chart colors", () => {
  it("chart-colors.css is colorStyles() over every chart", () => {
    const expected = `${HEADER}${colorStyles(everyChart().join("\n")).split("\n").sort().join("\n")}\n`;
    if (process.env.UPDATE_CHART_COLORS) writeFileSync(FILE, expected);
    expect(readFileSync(FILE, "utf8")).toBe(expected);
  });
});
