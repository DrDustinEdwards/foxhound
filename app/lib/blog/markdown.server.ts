// Markdown -> HTML renderer for blog posts. Ported from legacy lib/markdown.ts
// (Phase 6 Pass 2), rewritten for Workers:
//
//   - `:::diagram[slug]` is DROPPED. Legacy read public/diagrams/<slug>.svg
//     off local disk at request time via node:fs/node:path, which do not
//     exist on Workers. Legacy's own production fallback for a missing file
//     was to render nothing, so dropping the shortcode entirely (render
//     nothing) is not a regression, it matches legacy's already-live
//     behavior for the missing-asset case. If imported content leans on
//     this shortcode, a later pass can bundle diagram SVGs as importable
//     build-time assets; that is real extra work this pass does not need.
//   - `::bookmark[url]` no longer does a live server-side fetch to scrape
//     OG tags. That fetch ran on every SSR render of a post containing the
//     shortcode, so a slow or hanging external host would have blocked the
//     whole page render, in direct tension with "every marketing page
//     renders complete HTML server-side". It now renders a plain safe link
//     (domain shown as the visible text).
//   - `::postlink[slug]` resolution takes a Db handle and queries D1
//     instead of Supabase (see queries.server.ts's resolvePostLink).
//
// Configured once at module load: code blocks are highlighted with
// highlight.js (auto language detection when the fence has no language
// tag). External links get target="_blank" rel="noopener noreferrer";
// links to this site's own domains stay in-tab.
//
// Post-processing scans the rendered HTML for h2 / h3 to slugify ids and
// produce a TOC list. The highlight.js theme stylesheet is imported by the
// post detail route, not here.

import { marked, type Tokens, type Token } from "marked";
import hljs from "highlight.js";
import sanitizeHtml from "sanitize-html";

import type { Db } from "~/db";

import { generateSlug } from "./format";
import { resolvePostLink } from "./queries.server";

type LinkRendererThis = {
  parser: { parseInline: (tokens: Token[]) => string };
};

// Domains treated as "this site" for the external-link target behavior.
// Includes the legacy domain so imported posts that still reference old
// recovamrr.com URLs (pre-cutover content) don't get a needless
// target="_blank".
const INTERNAL_HOSTNAMES = /(^|\.)foxhoundapp\.com($|\/|:)|(^|\.)recovamrr\.com($|\/|:)/i;

// Author-body sanitize allowlist. Applied ONLY to HTML derived from the
// post markdown (the marked output and callout/toggle inner content).
// Trusted constructs (the YouTube embed, callout wrappers) are generated by
// this module and stitched in after sanitization, so they never pass
// through here. Raw <iframe>/<svg>/<script> in author body is discarded;
// embeds must go through the ::youtube shortcode.
const SANITIZE_OPTIONS: sanitizeHtml.IOptions = {
  allowedTags: [
    "p", "br", "hr",
    "h1", "h2", "h3", "h4", "h5", "h6",
    "ul", "ol", "li",
    "blockquote",
    "strong", "em", "b", "i", "del", "s", "sup", "sub",
    "code", "pre", "span",
    "a", "img",
    "table", "thead", "tbody", "tfoot", "tr", "th", "td",
  ],
  allowedAttributes: {
    a: ["href", "title", "target", "rel"],
    img: ["src", "alt", "title", "loading", "width", "height"],
    code: ["class"],
    pre: ["class"],
    span: ["class"],
    th: ["colspan", "rowspan", "align", "scope"],
    td: ["colspan", "rowspan", "align"],
  },
  // Relative URLs (/blog/..., #anchor) have no scheme and are kept.
  allowedSchemes: ["http", "https", "mailto"],
  allowedSchemesByTag: { img: ["http", "https"] },
  allowProtocolRelative: false,
  disallowedTagsMode: "discard",
};

function sanitizeBody(dirty: string): string {
  return sanitizeHtml(dirty, SANITIZE_OPTIONS);
}

let configured = false;

function configureMarked(): void {
  if (configured) return;
  configured = true;

  marked.use({
    async: false,
    gfm: true,
    breaks: false,
    renderer: {
      code({ text, lang }: Tokens.Code): string {
        const language = lang && hljs.getLanguage(lang) ? lang : "";
        const highlighted = language
          ? hljs.highlight(text, { language, ignoreIllegals: true }).value
          : hljs.highlightAuto(text).value;
        const cls = language ? `hljs language-${language}` : "hljs";
        return `<pre><code class="${cls}">${highlighted}</code></pre>`;
      },
      link({ href, title, tokens }: Tokens.Link): string {
        const self = this as unknown as LinkRendererThis;
        const text = self.parser.parseInline(tokens);
        const titleAttr = title ? ` title="${escapeAttr(title)}"` : "";
        const isExternal = /^https?:\/\//i.test(href) && !INTERNAL_HOSTNAMES.test(href);
        const targetAttrs = isExternal ? ' target="_blank" rel="noopener noreferrer"' : "";
        return `<a href="${escapeAttr(href)}"${titleAttr}${targetAttrs}>${text}</a>`;
      },
    },
  });
}

export interface TocItem {
  level: 2 | 3;
  text: string;
  id: string;
}

const CALLOUT_ICONS: Record<string, string> = {
  tip: "\u{1F4A1}",
  warning: "\u{26A0}\u{FE0F}",
  note: "\u{1F4DD}",
  danger: "\u{1F6A8}",
};

// Match fenced `:::type` ... `:::` blocks. Optional `[Header]` after the
// type feeds the toggle variant.
const FENCED_BLOCK_RE = /^:::([a-z]+)(?:\[([^\]]*)\])?\n([\s\S]*?)\n:::$/gm;
// `:::diagram[slug]` is a DROPPED shortcode (see module comment): legacy
// read an SVG off local disk at request time, which Workers cannot do.
// Matched and stripped to nothing before the fenced-block pass runs, the
// same single-line shape legacy used (no closing fence), so a stray
// `:::diagram[...]` never leaks into the rendered HTML as literal text.
const DIAGRAM_RE = /^:::diagram\[([a-z0-9-]+)\]$/gm;
const SHORTCODE_RE = /^::([a-z]+)\[([^\]]+)\]$/gm;
// Inline-friendly postlink matcher (not line-anchored, so it works mid-paragraph).
const POSTLINK_RE = /::postlink\[([^|\]]+)(?:\|([^\]]+))?\]/g;

type Replacement = { token: string; html: string };

function escapeAttr(s: string): string {
  return s.replace(/&/g, "&amp;").replace(/"/g, "&quot;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
}

function escapeText(s: string): string {
  return s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
}

function makeToken(i: number): string {
  return `\n\nXBLOGTOKEN${i}X\n\n`;
}

function renderCallout(type: string, content: string): string {
  const known = ["tip", "warning", "note", "danger"];
  const safeType = known.includes(type) ? type : "note";
  const icon = CALLOUT_ICONS[safeType] ?? CALLOUT_ICONS.note;
  const inner = sanitizeBody(marked.parse(content, { async: false }) as string);
  return `<div class="blog-callout blog-callout-${safeType}"><span class="blog-callout-icon" aria-hidden="true">${icon}</span><div class="blog-callout-content">${inner}</div></div>`;
}

function renderPullquote(content: string): string {
  return `<blockquote class="blog-pullquote">${escapeText(content.trim())}</blockquote>`;
}

interface FaqPair {
  q: string;
  a: string;
}

function parseFaqPairs(content: string): FaqPair[] {
  const pairs: FaqPair[] = [];
  let currentQ: string | null = null;
  let currentA: string[] = [];

  function flush() {
    if (currentQ && currentA.length > 0) {
      pairs.push({ q: currentQ.trim(), a: currentA.join(" ").trim() });
    }
    currentQ = null;
    currentA = [];
  }

  for (const raw of content.split("\n")) {
    const line = raw.trim();
    if (line.startsWith("Q:")) {
      flush();
      currentQ = line.slice(2).trim();
    } else if (line.startsWith("A:")) {
      currentA = [line.slice(2).trim()];
    } else if (line === "") {
      // blank, ignore
    } else if (currentA.length > 0) {
      currentA.push(line);
    }
  }
  flush();
  return pairs;
}

// Scan a raw post body for every :::faq block and return the flattened Q/A
// list. Used by blog/post.tsx to build FAQPage JSON-LD directly from the raw
// body, decoupled from the renderer's HTML structure. Returns [] for posts
// with no :::faq blocks. Pure; does not require renderMarkdown to have run.
export function extractFaqPairs(body: string): Array<{ question: string; answer: string }> {
  const pairs: Array<{ question: string; answer: string }> = [];
  const blockRe = /^:::faq(?:\[[^\]]*\])?\n([\s\S]*?)\n:::$/gm;
  let m: RegExpExecArray | null;
  while ((m = blockRe.exec(body)) !== null) {
    for (const p of parseFaqPairs(m[1])) {
      pairs.push({ question: p.q, answer: p.a });
    }
  }
  return pairs;
}

function renderFaq(content: string): string {
  const pairs = parseFaqPairs(content);
  if (pairs.length === 0) return "";
  const items = pairs
    .map(
      ({ q, a }) =>
        `<div class="blog-faq-item"><dt class="blog-faq-question">${escapeText(q)}</dt><dd class="blog-faq-answer">${escapeText(a)}</dd></div>`,
    )
    .join("");
  return `<div class="blog-faq" data-faq="true"><dl class="blog-faq-list">${items}</dl></div>`;
}

function renderToggle(header: string, content: string): string {
  const headerHtml = escapeText(header.trim());
  const inner = sanitizeBody(marked.parse(content, { async: false }) as string);
  return `<details class="blog-toggle"><summary class="blog-toggle-header">${headerHtml}</summary><div class="blog-toggle-content">${inner}</div></details>`;
}

function renderYouTube(idOrUrl: string): string {
  const id = extractYouTubeId(idOrUrl);
  if (!id) return "";
  return `<div class="blog-embed blog-embed-youtube"><iframe src="https://www.youtube-nocookie.com/embed/${encodeURIComponent(id)}" title="YouTube video" loading="lazy" allowfullscreen frameborder="0"></iframe></div>`;
}

function extractYouTubeId(input: string): string | null {
  const trimmed = input.trim();
  if (/^[a-zA-Z0-9_-]{11}$/.test(trimmed)) return trimmed;
  try {
    const u = new URL(trimmed);
    if (u.hostname === "youtu.be") {
      const id = u.pathname.replace(/^\//, "").split("/")[0];
      return id && /^[a-zA-Z0-9_-]{11}$/.test(id) ? id : null;
    }
    if (/(^|\.)youtube(-nocookie)?\.com$/.test(u.hostname)) {
      const v = u.searchParams.get("v");
      if (v && /^[a-zA-Z0-9_-]{11}$/.test(v)) return v;
      const path = u.pathname.split("/").filter(Boolean);
      if (path.length >= 2 && /^(embed|shorts|v)$/.test(path[0])) {
        const id = path[1];
        if (/^[a-zA-Z0-9_-]{11}$/.test(id)) return id;
      }
    }
  } catch {
    return null;
  }
  return null;
}

// Simplified from legacy's renderBookmark: no live OG-tag fetch (see the
// module comment). A plain, safe outbound link with the hostname as the
// visible label.
function renderBookmark(url: string): string {
  const safe = url.trim();
  try {
    const host = new URL(safe).host.replace(/^www\./, "");
    return `<a href="${escapeAttr(safe)}" target="_blank" rel="noopener noreferrer" class="blog-bookmark-link">${escapeText(host)}</a>`;
  } catch {
    return `<a href="${escapeAttr(safe)}" target="_blank" rel="noopener noreferrer">${escapeText(safe)}</a>`;
  }
}

function addHeadingIds(html: string): { html: string; toc: TocItem[] } {
  const toc: TocItem[] = [];
  const used = new Map<string, number>();
  const out = html.replace(/<(h2|h3)>([\s\S]*?)<\/\1>/g, (_match, tag: string, inner: string) => {
    const text = stripTags(inner).trim();
    const baseId = generateSlug(text) || "section";
    const count = used.get(baseId) ?? 0;
    used.set(baseId, count + 1);
    const id = count === 0 ? baseId : `${baseId}-${count + 1}`;
    const level: 2 | 3 = tag === "h2" ? 2 : 3;
    toc.push({ level, text, id });
    return `<${tag} id="${id}">${inner}</${tag}>`;
  });
  return { html: out, toc };
}

function stripTags(s: string): string {
  return s.replace(/<[^>]+>/g, "");
}

export async function renderMarkdown(db: Db, body: string): Promise<{ html: string; toc: TocItem[] }> {
  configureMarked();

  const replacements: Replacement[] = [];
  const stash = (html: string): string => {
    const token = makeToken(replacements.length);
    replacements.push({ token: token.trim(), html });
    return token;
  };

  // 1. Single-line :::diagram[slug] shortcodes, stripped to nothing
  //    (dropped shortcode, see module comment). Processed before the
  //    fenced-block pass so a stray `:::diagram[...]` is never mistaken
  //    for the opening of a fenced block.
  let pre = body.replace(DIAGRAM_RE, () => stash(""));

  // 2. Fenced custom blocks.
  pre = pre.replace(FENCED_BLOCK_RE, (_m, kind: string, header: string | undefined, content: string) => {
    const k = kind.toLowerCase();
    if (k === "pullquote") return stash(renderPullquote(content));
    if (k === "toggle") return stash(renderToggle(header ?? "", content));
    if (k === "faq") return stash(renderFaq(content));
    if (["tip", "warning", "note", "danger"].includes(k)) {
      return stash(renderCallout(k, content));
    }
    return stash(renderCallout("note", content));
  });

  // 3. Inline postlinks, matched before line-anchored shortcodes so
  //    `::postlink[slug]` works inside paragraphs.
  const inlineSlots: Array<{ token: string; slug: string; display: string | null }> = [];
  pre = pre.replace(POSTLINK_RE, (_m, slug: string, display: string | undefined) => {
    const token = `XBLOGPLINK${inlineSlots.length}X`;
    const displayTrimmed = display?.trim() ?? "";
    inlineSlots.push({
      token,
      slug: slug.trim(),
      display: displayTrimmed.length > 0 ? displayTrimmed : null,
    });
    return token;
  });

  // 4. One-line shortcodes (youtube, bookmark). Both resolve synchronously
  //    now that bookmark no longer fetches, but kept as a resolve() slot
  //    shape for parity with the postlink resolution below.
  type Slot = { token: string; resolve: () => string };
  const slots: Slot[] = [];
  pre = pre.replace(SHORTCODE_RE, (_m, kind: string, arg: string) => {
    const k = kind.toLowerCase();
    const token = makeToken(replacements.length + slots.length);
    if (k === "youtube") {
      slots.push({ token: token.trim(), resolve: () => renderYouTube(arg) });
    } else if (k === "bookmark") {
      slots.push({ token: token.trim(), resolve: () => renderBookmark(arg) });
    } else {
      slots.push({ token: token.trim(), resolve: () => `<code>${escapeText(`::${kind}[${arg}]`)}</code>` });
    }
    return token;
  });

  for (const s of slots) {
    replacements.push({ token: s.token, html: s.resolve() });
  }

  const resolvedInline = await Promise.all(
    inlineSlots.map(async (s) => {
      const target = await resolvePostLink(db, s.slug);
      if (target) {
        const text = s.display ?? target.title;
        return `<a href="/blog/${escapeAttr(target.slug)}">${escapeText(text)}</a>`;
      }
      const raw = s.display ? `::postlink[${s.slug}|${s.display}]` : `::postlink[${s.slug}]`;
      return `<code>${escapeText(raw)}</code>`;
    }),
  );

  let html = sanitizeBody(marked.parse(pre, { async: false }) as string);

  for (let i = 0; i < inlineSlots.length; i++) {
    html = html.split(inlineSlots[i].token).join(resolvedInline[i]);
  }

  for (const { token, html: replacement } of replacements) {
    const wrapped = `<p>${token}</p>`;
    if (html.includes(wrapped)) {
      html = html.split(wrapped).join(replacement);
    } else {
      html = html.split(token).join(replacement);
    }
  }

  const withIds = addHeadingIds(html);
  return { html: withIds.html, toc: withIds.toc };
}
