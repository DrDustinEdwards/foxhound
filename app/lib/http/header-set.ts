// THE SECURITY HEADER SET, from site-runtime (RULES.md 4.2; Q4, Dustin "yes",
// 2026-10-14; J22 row F16). The values are OWASP Secure Headers Project's own,
// read by site-runtime; where Foxhound must differ is its entry in the site
// registry, each deviation with its reason.
//
// Two places apply it. The Worker (content-security-policy.ts,
// applySecurityHeaders) stamps it on every response the Worker makes, redirects
// and errors included. public/_headers carries it for static assets, which
// Cloudflare's asset server answers WITHOUT running the Worker (run_worker_first
// stays off, RULES.md 4.2); every build writes that file from this set
// (scripts/gen-headers.mjs), so it cannot drift.
//
// This module imports only the package, never a `~/` path or a relative file,
// so scripts/gen-headers.mjs can load it with Node's type stripping.
//
// RULES.md 4.1 is the floor: nothing here is weaker than Foxhound's pre-J22 set
// (HSTS one year, X-Frame-Options DENY, nosniff, strict-origin-when-cross-origin,
// camera/microphone/geolocation/payment denied) or Recova's next.config.ts
// (blob 8cf9b0c7).
//
// What the standard brings over the pre-J22 set, taken as is: HSTS two years
// (no preload, as before: add it only once the foxhoundapp.com apex is verified
// HTTPS-only, TASK-foxhound-security-headers.md), Cross-Origin-Opener-Policy
// same-origin (Stripe Checkout and Connect are top-level redirects, Turnstile is
// an iframe, so nothing relies on a cross-origin opener), Cross-Origin-Resource-
// Policy same-origin as the default (the images other origins embed are opened
// up below, by file type; a webmail client that loads the email
// open pixel directly still makes the request the open is recorded from),
// X-DNS-Prefetch-Control off (Recova sent "on"), X-Permitted-Cross-Domain-
// Policies none, and OWASP's full Permissions-Policy list.

import { TDM_RESERVATION_HEADERS } from "@drdustinedwards/site-helpers/robots";
import { buildSecurityHeaders, corpFor, headersFile } from "@dustinedwards/site-runtime/headers";
import { foxhound } from "@dustinedwards/site-runtime/sites";

// Foxhound's entry in site-runtime's site registry (./sites, `foxhound`)
// holds its deviations and their reasons: Referrer-Policy
// strict-origin-when-cross-origin (Better Auth refuses the `Origin: null` that
// no-referrer causes) and Permissions-Policy allowing passkeys and
// clipboard-write for this origin. Prelum's TDMRep header goes beside it,
// reserving training rights as /ai.txt says.
export const SECURITY_HEADERS: Readonly<Record<string, string>> = Object.freeze({
  ...buildSecurityHeaders({ site: foxhound }),
  ...TDM_RESERVATION_HEADERS,
});

// Cross-Origin-Resource-Policy by file type (site-runtime's corpFor): the
// images, scripts, styles and fonts here may be loaded by other origins (the
// favicons beside a Foxhound link, the RSS channel image); a page keeps the
// standard's same-origin. The og cards are Worker responses and set it there.
const STATIC_TYPES: Readonly<Record<string, string>> = {
  ico: "image/x-icon",
  png: "image/png",
  svg: "image/svg+xml",
  css: "text/css",
  js: "text/javascript",
  woff2: "font/woff2",
};

/** The whole of public/_headers, through site-runtime's headersFile; the build writes it (scripts/gen-headers.mjs). */
export function renderStaticHeadersFile(): string {
  return headersFile(SECURITY_HEADERS, {
    comment: [
      "GENERATED by scripts/gen-headers.mjs from app/lib/http/header-set.ts, on every build.",
      "Static files are served without the Worker, so they carry the same set here.",
      "No Content-Security-Policy: Foxhound's pages carry a per-request one.",
    ],
    charset: true,
    paths: {
      ...Object.fromEntries(
        Object.entries(STATIC_TYPES).map(([ext, type]) => [`/*.${ext}`, { "Cross-Origin-Resource-Policy": corpFor(type) }]),
      ),
      "/assets/*": { "Cache-Control": "public, max-age=31536000, immutable" },
      // The islands /site.js starts, each named by its content (devkit's siteScript).
      "/islands/*": { "Cache-Control": "public, max-age=31536000, immutable" },
    },
  });
}
